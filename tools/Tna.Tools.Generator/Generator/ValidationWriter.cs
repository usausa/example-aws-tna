namespace Tna.Generator;

using System.Globalization;
using System.Text;

// Tna.Contracts の要求の本文の検証。コンポーネントのオブジェクトごとのメソッドと、関数と画面が使う登録と、
// JSON の読み取りで求める必須の項目を書く
internal static class ValidationWriter
{
    public static IEnumerable<(string Pattern, string Candidate)> Patterns(ValidationModel model) =>
        model.Objects.SelectMany(static x => x.Properties).SelectMany(static x => Patterns(x.Shape));

    public static string Build(ValidationModel model, PatternRegistry patterns)
    {
        var objects = model.Objects.OrderBy(static x => x.Name, StringComparer.Ordinal).ToList();
        var code = new CodeBuilder();
        code.Line("// <auto-generated>");
        code.Line($"// tools/Tna.Tools.Generator が {model.File} から作った。手で直さない。");
        code.Line("// </auto-generated>");
        code.Line("#nullable enable");
        code.Line();
        code.Line($"namespace {model.Namespace};");
        code.Line();
        code.Line("using System.Globalization;");
        code.Line("using System.Linq;");
        if (model.Namespace != "Tna.Contracts")
        {
            code.Line();
            code.Line("using Tna.Contracts;");
        }

        code.Line();
        code.Line($"// 要求の本文の型と、そこから届く型 ({objects.Count} の型) の検証");
        code.Line($"public static class {model.ClassName}");
        code.Open();
        code.Line("public static ContractChecks Checks { get; } = new ContractChecks.Builder()");
        foreach (var x in objects)
        {
            code.Line($"    .Check<{x.Name}>(Check{x.Name})");
        }

        foreach (var x in objects.Where(static x => x.RequiredNames.Count > 0))
        {
            code.Line($"    .Required<{x.Name}>({Names(x.RequiredNames)})");
        }

        foreach (var registration in objects.SelectMany(Registrations))
        {
            code.Line("    " + registration);
        }

        code.Line("    .Build();");
        var polymorphic = objects.Where(static x => x.DerivedNames.Count > 0).Select(static x => x.Name).ToHashSet(StringComparer.Ordinal);
        foreach (var x in objects)
        {
            code.Line();
            code.Line($"private static void Check{x.Name}({x.Name} value, InputCheck check, string path)");
            code.Open();
            var writer = new MethodWriter(code, patterns, polymorphic);
            if (x.BaseName is not null)
            {
                code.Line($"Check{x.BaseName}(value, check, path);");
            }

            foreach (var property in x.Properties)
            {
                writer.Value($"value.{property.CSharpName}", $"path + \"/{property.JsonName}\"", property.Shape, property.Required);
            }

            code.Close();
        }

        // プロパティの中の種類で形が変わる型の値は、実行時の型で、その種類のプロパティまで確かめる
        foreach (var x in objects.Where(static x => x.DerivedNames.Count > 0))
        {
            code.Line();
            code.Line($"private static void CheckAny{x.Name}({x.Name} value, InputCheck check, string path)");
            code.Open();
            code.Line("switch (value)");
            code.Open();
            foreach (var derived in x.DerivedNames)
            {
                code.Line($"case {derived} derived:");
                code.Line($"    Check{derived}(derived, check, path);");
                code.Line("    break;");
            }

            code.Line("default:");
            code.Line($"    Check{x.Name}(value, check, path);");
            code.Line("    break;");
            code.Close();
            code.Close();
        }

        code.Close();
        return code.ToString();
    }

    // 値に確かめることがあるか (確かめることのない値にはコードを書かない)
    public static bool HasChecks(ValueShape shape, bool required)
    {
        var mustExist = required && !shape.Nullable;
        return shape.Kind switch
        {
            ValueKind.Text => mustExist || shape.MinLength.HasValue || shape.MaxLength.HasValue || (shape.Pattern is not null) || (shape.Format is not null) || (shape.Constant is not null),
            ValueKind.Number => shape.Minimum.HasValue || shape.Maximum.HasValue || shape.ExclusiveMinimum.HasValue || shape.ExclusiveMaximum.HasValue || shape.MultipleOf.HasValue,
            ValueKind.Enum or ValueKind.Object => true,
            ValueKind.InlineObject => mustExist || shape.Inline!.Properties.Any(static x => HasChecks(x.Shape, x.Required)),
            ValueKind.Array => mustExist || shape.MinItems.HasValue || shape.MaxItems.HasValue || HasChecks(shape.Items!, true),
            ValueKind.Map => HasChecks(shape.Items!, true),
            _ => false
        };
    }

    private static IEnumerable<(string Pattern, string Candidate)> Patterns(ValueShape shape)
    {
        if (shape.Pattern is not null)
        {
            yield return (shape.Pattern, shape.PatternName!);
        }

        var children = shape.Kind switch
        {
            ValueKind.InlineObject => shape.Inline!.Properties.Select(static x => x.Shape),
            ValueKind.Array or ValueKind.Map => [shape.Items!],
            _ => []
        };
        foreach (var pattern in children.SelectMany(Patterns))
        {
            yield return pattern;
        }
    }

    // プロパティのスキーマに書いたオブジェクトの必須の項目。クラスの名前は型の生成が付けるため、コンポーネントから
    // プロパティをたどって型を見つける (式は動かさない)
    private static IEnumerable<string> Registrations(ObjectModel owner)
    {
        var registrations = new List<string>();
        foreach (var property in owner.Properties)
        {
            Collect(owner.Name, property, new Selector($"x.{property.CSharpName}", false), registrations);
        }

        return registrations;
    }

    private static void Collect(string owner, PropertyModel property, Selector selector, List<string> registrations)
    {
        var shape = property.Shape;
        switch (shape.Kind)
        {
            case ValueKind.InlineObject:
                if (shape.Inline!.RequiredNames.Count > 0)
                {
                    var method = selector.Sequence ? "RequiredItems" : "Required";
                    registrations.Add($".{method}(({owner} x) => {selector.Expression}, {Names(shape.Inline.RequiredNames)})");
                }

                foreach (var child in shape.Inline.Properties)
                {
                    Collect(owner, child, selector.Member(child.CSharpName, child.Shape.Kind == ValueKind.Array), registrations);
                }

                break;
            case ValueKind.Array when shape.Items!.Kind is ValueKind.InlineObject or ValueKind.Array:
                Collect(owner, property with { Shape = shape.Items }, selector with { Sequence = true }, registrations);
                break;
        }
    }

    private static string Names(IEnumerable<string> names) => String.Join(", ", names.Select(static x => $"\"{x}\""));

    private static string Number(double value) => value.ToString("R", CultureInfo.InvariantCulture);

    // コンポーネント (x) からプロパティまでの式。1つのオブジェクトか、配列の要素
    private sealed record Selector(string Expression, bool Sequence)
    {
        public Selector Member(string name, bool array) =>
            Sequence
                ? new Selector($"{Expression}!.{(array ? "SelectMany" : "Select")}(e => e!.{name}!)", true)
                : new Selector($"{Expression}!.{name}", array);
    }

    // 検証のメソッドの文。変数には毎回新しい名前を付ける。種類で形が変わる型は実行時の型で確かめる
    private sealed class MethodWriter
    {
        private readonly CodeBuilder code;

        private readonly PatternRegistry patterns;

        private readonly HashSet<string> polymorphic;

        private int counter;

        public MethodWriter(CodeBuilder code, PatternRegistry patterns, HashSet<string> polymorphic)
        {
            this.code = code;
            this.patterns = patterns;
            this.polymorphic = polymorphic;
        }

        public void Value(string value, string field, ValueShape shape, bool required)
        {
            if (!HasChecks(shape, required))
            {
                return;
            }

            var mustExist = required && !shape.Nullable;
            switch (shape.Kind)
            {
                case ValueKind.Text:
                    code.Line($"check.Text({field}, {value}, {(mustExist ? "true" : "false")}{TextArguments(shape)});");
                    break;
                case ValueKind.Number:
                    code.Line($"check.Number({field}, {value}{NumberArguments(shape)});");
                    break;
                case ValueKind.Enum:
                    code.Line($"check.Defined({field}, {value});");
                    break;
                case ValueKind.Object:
                    var method = polymorphic.Contains(shape.ObjectName!) ? "CheckAny" : "Check";
                    Block(value, field, mustExist, item => code.Line($"{method}{shape.ObjectName}({item}, check, {field});"));
                    break;
                case ValueKind.InlineObject:
                    Block(value, field, mustExist, item =>
                    {
                        var path = Name("p");
                        code.Line($"var {path} = {field};");
                        foreach (var property in shape.Inline!.Properties)
                        {
                            Value($"{item}.{property.CSharpName}", $"{path} + \"/{property.JsonName}\"", property.Shape, property.Required);
                        }
                    });
                    break;
                case ValueKind.Array:
                    Block(value, field, mustExist, items =>
                    {
                        if (shape.MinItems.HasValue || shape.MaxItems.HasValue)
                        {
                            code.Line($"check.Count({field}, {items}.Count{CountArguments(shape)});");
                        }

                        if (HasChecks(shape.Items!, true))
                        {
                            var path = Name("p");
                            var index = Name("i");
                            var item = Name("item");
                            code.Line($"var {path} = {field};");
                            code.Line($"var {index} = 0;");
                            code.Line($"foreach (var {item} in {items})");
                            code.Open();
                            Value(item, $"{path} + \"/\" + {index}.ToString(CultureInfo.InvariantCulture)", shape.Items!, true);
                            code.Line($"{index}++;");
                            code.Close();
                        }
                    });
                    break;
                case ValueKind.Map:
                    Block(value, field, false, entries =>
                    {
                        var path = Name("p");
                        var key = Name("key");
                        var item = Name("item");
                        code.Line($"var {path} = {field};");
                        code.Line($"foreach (var ({key}, {item}) in {entries})");
                        code.Open();
                        Value(item, $"{path} + \"/\" + InputCheck.Escape({key})", shape.Items!, true);
                        code.Close();
                    });
                    break;
            }
        }

        // 値があるときだけ先を確かめ、必須の値がなければ誤りにする
        private void Block(string value, string field, bool mustExist, Action<string> body)
        {
            var name = Name("v");
            code.Line($"if ({value} is {{ }} {name})");
            code.Open();
            body(name);
            code.Close();
            if (mustExist)
            {
                code.Line("else");
                code.Open();
                code.Line($"check.Missing({field}, true);");
                code.Close();
            }
        }

        private string Name(string prefix) => prefix + (++counter).ToString(CultureInfo.InvariantCulture);

        private string TextArguments(ValueShape shape)
        {
            var arguments = new List<string>();
            if (shape.MinLength is { } min)
            {
                arguments.Add($"minLength: {min.ToString(CultureInfo.InvariantCulture)}");
            }

            if (shape.MaxLength is { } max)
            {
                arguments.Add($"maxLength: {max.ToString(CultureInfo.InvariantCulture)}");
            }

            if (shape.Pattern is not null)
            {
                arguments.Add($"pattern: ContractPatterns.{patterns.NameOf(shape.Pattern)}()");
            }

            if (shape.Format is not null)
            {
                arguments.Add("format: TextFormat." + shape.Format switch { "email" => "Email", "uri" => "Uri", _ => "UriReference" });
            }

            if (shape.Constant is not null)
            {
                arguments.Add($"constant: \"{shape.Constant}\"");
            }

            return String.Concat(arguments.Select(static x => ", " + x));
        }

        private static string NumberArguments(ValueShape shape)
        {
            (string Name, double? Value)[] bounds =
            [
                ("minimum", shape.Minimum), ("maximum", shape.Maximum), ("exclusiveMinimum", shape.ExclusiveMinimum),
                ("exclusiveMaximum", shape.ExclusiveMaximum), ("multipleOf", shape.MultipleOf)
            ];
            return String.Concat(bounds.Where(static x => x.Value.HasValue).Select(static x => $", {x.Name}: {Number(x.Value!.Value)}"));
        }

        private static string CountArguments(ValueShape shape) =>
            (shape.MinItems is { } min ? $", minItems: {min.ToString(CultureInfo.InvariantCulture)}" : String.Empty) +
            (shape.MaxItems is { } max ? $", maxItems: {max.ToString(CultureInfo.InvariantCulture)}" : String.Empty);
    }
}

// 生成する C# のファイルの行。ブロックの深さで字下げする
internal sealed class CodeBuilder
{
    private readonly StringBuilder builder = new();

    private int depth;

    public void Line(string text = "") =>
        builder.Append(text.Length == 0 ? String.Empty : new string(' ', depth * 4) + text).Append("\r\n");

    public void Open()
    {
        Line("{");
        depth++;
    }

    public void Close()
    {
        depth--;
        Line("}");
    }

    public override string ToString() => builder.ToString();
}
