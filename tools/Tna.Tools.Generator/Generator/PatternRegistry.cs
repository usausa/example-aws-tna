namespace Tna.Generator;

using System.Globalization;
using System.Text;

// 仕様のパターン。それぞれに Tna.Contracts の ContractPatterns の名前を1つ付ける。スキーマのパターンはスキーマの名前
// (Ulid) を取り、候補のうち短いものを選ぶ (NullableUlid より Ulid)
internal sealed class PatternRegistry
{
    public const string OutputFile = "src/Tna.Contracts/Contracts/ContractPatterns.g.cs";

    private readonly SortedDictionary<string, string> names;

    private PatternRegistry(SortedDictionary<string, string> names)
    {
        this.names = names;
    }

    public static PatternRegistry Create(IEnumerable<(string Pattern, string Candidate)> uses)
    {
        var names = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var taken = new HashSet<string>(StringComparer.Ordinal);
        foreach (var group in uses.GroupBy(static x => x.Pattern, StringComparer.Ordinal).OrderBy(static x => x.Key, StringComparer.Ordinal))
        {
            var name = group.Select(static x => x.Candidate).Distinct(StringComparer.Ordinal).OrderBy(static x => x.Length).ThenBy(static x => x, StringComparer.Ordinal).First();
            var unique = name;
            for (var i = 2; !taken.Add(unique); i++)
            {
                unique = name + i.ToString(CultureInfo.InvariantCulture);
            }

            names[group.Key] = unique;
        }

        return new PatternRegistry(names);
    }

    public string NameOf(string pattern) => names[pattern];

    public string Build()
    {
        var builder = new StringBuilder();
        void Line(string text = "") => builder.Append(text).Append("\r\n");

        Line("// <auto-generated>");
        Line("// tools/Tna.Tools.Generator が OpenAPI の文書 (docs/api/dist) から作った。手で直さない。");
        Line("// </auto-generated>");
        Line("#nullable enable");
        Line();
        Line("namespace Tna.Contracts;");
        Line();
        Line("using System.Text.RegularExpressions;");
        Line();
        Line("// 仕様のパターン。JSON Schema と同じく、$ は文字列の終わり (最後の改行の前ではない)");
        Line("public static partial class ContractPatterns");
        Line("{");
        var first = true;
        foreach (var (pattern, name) in names.OrderBy(static x => x.Value, StringComparer.Ordinal))
        {
            if (!first)
            {
                Line();
            }

            first = false;
            Line($"    [GeneratedRegex(@\"{ToDotNet(pattern).Replace("\"", "\"\"", StringComparison.Ordinal)}\", RegexOptions.CultureInvariant)]");
            Line($"    public static partial Regex {name}();");
        }

        Line("}");
        return builder.ToString();
    }

    // .NET の $ は最後の改行の前にも当たるため、終わりだけに当たる \z にする
    private static string ToDotNet(string pattern) =>
        pattern.EndsWith('$') && !pattern.EndsWith("\\$", StringComparison.Ordinal) ? pattern[..^1] + "\\z" : pattern;
}
